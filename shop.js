const formatMoney = (amount) => `$${amount.toFixed(2)}`;

const readCart = () => {
  try {
    return JSON.parse(localStorage.getItem(CHICWAY_CART_KEY) || "[]");
  } catch {
    return [];
  }
};

const writeCart = (cart) => {
  localStorage.setItem(CHICWAY_CART_KEY, JSON.stringify(cart));
  updateCartCounts();
};

const findProduct = (id) => PRODUCTS.find((product) => product.id === id) || PRODUCTS[0];

const addToCart = (id, quantity = 1) => {
  const cart = readCart();
  const existing = cart.find((item) => item.id === id);

  if (existing) {
    existing.quantity += quantity;
  } else {
    cart.push({ id, quantity });
  }

  writeCart(cart);
};

const updateQuantity = (id, delta) => {
  const cart = readCart()
    .map((item) => item.id === id ? { ...item, quantity: item.quantity + delta } : item)
    .filter((item) => item.quantity > 0);

  writeCart(cart);
  renderCart();
};

const cartQuantity = () => readCart().reduce((sum, item) => sum + item.quantity, 0);

const updateCartCounts = () => {
  const count = cartQuantity();

  document.querySelectorAll("[data-cart-count]").forEach((badge) => {
    badge.textContent = count;
    badge.hidden = count === 0;
  });
};

const productCard = (product) => {
  const hasPrice = Number.isFinite(product.price);

  return `
    <article class="product-card">
      <a href="${product.detailPath || `product-detail.html?id=${product.id}`}" aria-label="View ${product.name}">
        <img src="${product.image}" alt="${product.name}" loading="lazy" decoding="async">
      </a>
      <div class="product-body">
        <h3>${product.name}</h3>
        <p>${product.short}</p>
        <div class="price-row${hasPrice ? "" : " no-price"}">
          ${hasPrice ? `<span class="price">${formatMoney(product.price)}</span>` : ""}
          ${product.buyUrl
            ? `<a class="small-btn" href="${product.buyUrl}" target="_blank" rel="noopener noreferrer" data-product-id="${product.id}">Buy Now</a>`
            : `<a class="small-btn details-btn" href="${product.detailPath || `product-detail.html?id=${product.id}`}">View Details</a>`}
        </div>
      </div>
    </article>
  `;
};

const renderProducts = () => {
  const grid = document.querySelector("[data-products-grid]");

  if (!grid || grid.dataset.prerendered === "true") {
    return;
  }

  grid.innerHTML = PRODUCTS
    .filter((product) => product.showInCatalog !== false)
    .map(productCard)
    .join("");
};

